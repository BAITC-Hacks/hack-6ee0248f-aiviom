export function serverMessage(locale: Locale, key: MessageKey | `business.${string}`, params: Params = {}): string {
  const specific = key.startsWith('business.') ? Object.values(businessErrors).find(item => `business.${item.key}` === key) : undefined;
  const template = specific ? specific[locale] : messages[locale][key as MessageKey] ?? messages[locale]['error.validation'];
  return template.replace(/\{([a-z_]+)\}/g, (_match, name: string) => String(params[name] ?? ''));
}


export const dictionaries: Record<Locale, Dictionary & ExtraDictionary> = {
  ru: { ...ru, ...extraRu },
  kk: { ...kk, ...extraKk },
  en: { ...en, ...extraEn },
};
export type TranslationParams = Record<
  string,
  string | number | boolean | null | undefined
>;

/** Only named parameters are substituted; values are plain text and React escapes them. */
export function translate(
  locale: Locale,
  key: TranslationKey | (string & {}),
  params?: TranslationParams,
): string {
  const template =
    (dictionaries[locale] as Record<string, string>)[key] ??
    (dictionaries.ru as Record<string, string>)[key] ??
    key
      .split(".")
      .at(-1)!
      .replace(/([a-z])([A-Z])/g, "$1 $2")
      .replaceAll("_", " ");
  return template.replace(
    /\{([a-zA-Z][a-zA-Z0-9_]*)\}/g,
    (match, name: string) => {
      const value = params?.[name];
      return value == null ? match : String(value);
    },
  );
}

export function formatNumberFor(
  locale: Locale,
  value: number | null | undefined,
  options?: Intl.NumberFormatOptions,
): string {
  return value == null || !Number.isFinite(value)
    ? "—"
    : new Intl.NumberFormat(
        localeTags[locale],
        options ?? { maximumFractionDigits: 1 },
      ).format(value);
}

export function formatPercentFor(
  locale: Locale,
  value: number | null | undefined,
): string {
  return value == null || !Number.isFinite(value)
    ? translate(locale, "common.noData")
    : `${formatNumberFor(locale, value)}%`;
}

/** A YYYY-MM-DD value is a calendar date, never an instant in the viewer's time zone. */
export function formatDateFor(
  locale: Locale,
  value: string | null | undefined,
  options?: Intl.DateTimeFormatOptions,
): string {
  if (!value) return "—";
  const dateOnly = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value);
  const date = dateOnly
    ? new Date(
        Date.UTC(
          Number(dateOnly[1]),
          Number(dateOnly[2]) - 1,
          Number(dateOnly[3]),
          12,
        ),
      )
    : new Date(value);
  if (Number.isNaN(date.getTime())) return "—";
  return new Intl.DateTimeFormat(localeTags[locale], {
    day: "2-digit",
    month: locale === "kk" ? "2-digit" : "short",
    year: "numeric",
    ...(dateOnly ? { timeZone: "UTC" } : {}),
    ...options,
  }).format(date);
}

export type PluralForms = {
  one: string;
  few?: string;
  many?: string;
  other: string;
};
export function pluralFor(
  locale: Locale,
  count: number,
  forms: PluralForms,
): string {
  const category = new Intl.PluralRules(localeTags[locale]).select(count);
  const form = forms[category as keyof PluralForms] ?? forms.other;
  return form.replace(
    /\{count\}/g,
    formatNumberFor(locale, count, { maximumFractionDigits: 0 }),
  );
}

export function enumTextFor(
  locale: Locale,
  group: "status" | "role" | "grade" | "format" | "type" | "reason",
  value: string | null | undefined,
): string {
  if (!value) return translate(locale, "common.notSpecified");
  if (group !== "role" && group !== "reason") {
    const sharedKind: EnumKind = group === "type" ? "eventType" : group;
    const shared = sourceEnumText(locale, sharedKind, value);
    if (shared !== value) return shared;
  }
  const key = `${group}.${value}` as TranslationKey;
  return Object.prototype.hasOwnProperty.call(dictionaries.ru, key)
    ? translate(locale, key)
    : value.replaceAll("_", " ");
}

export function catalogTextFor(
  locale: Locale,
  id: string,
  field: string,
  fallback: string,
): string {
  const catalogField: CatalogField = [
    "title",
    "description",
    "deliverables",
    "criteria",
    "reason",
    "evidence",
  ].includes(field)
    ? (field as CatalogField)
    : "title";
  let kind: CatalogKind;
  if (id.startsWith("EV_")) kind = "event";
  else if (id.startsWith("SK_")) kind = "skill";
  else if (id.startsWith("DEMO_")) kind = "demo";
  else if (id === "mentor" || id === "project") kind = "reward";
  else {
    const role = sourceCatalogText(locale, "role", id, fallback, catalogField);
    return role !== fallback
      ? role
      : sourceCatalogText(locale, "department", id, fallback, catalogField);
  }
  return sourceCatalogText(locale, kind, id, fallback, catalogField);
}

type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (
    key: TranslationKey | (string & {}),
    params?: TranslationParams,
  ) => string;
  formatNumber: (
    value: number | null | undefined,
    options?: Intl.NumberFormatOptions,
  ) => string;
  formatDate: (
    value: string | null | undefined,
    options?: Intl.DateTimeFormatOptions,
  ) => string;
  formatPercent: (value: number | null | undefined) => string;
  plural: (count: number, forms: PluralForms) => string;
  enumText: (
    group: "status" | "role" | "grade" | "format" | "type" | "reason",
    value: string | null | undefined,
  ) => string;
  catalogText: (id: string, field: string, fallback: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function storedLocale(): Locale {
  try {
    return normalizeLocale(window.localStorage.getItem(STORAGE_KEY));
  } catch {
    return "ru";
  }
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(storedLocale);
  const setLocale = useCallback(
    (next: Locale) => setLocaleState(normalizeLocale(next)),
    [],
  );
  useEffect(() => {
    document.documentElement.lang = locale;
    document.title = `${translate(locale, "app.title")} · ${translate(locale, "app.subtitle")}`;
    try {
      window.localStorage.setItem(STORAGE_KEY, locale);
    } catch {
      /* Storage may be disabled. */
    }
  }, [locale]);
  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale,
      t: (key, params) => translate(locale, key, params),
      formatNumber: (number, options) =>
        formatNumberFor(locale, number, options),
      formatDate: (date, options) => formatDateFor(locale, date, options),
      formatPercent: (number) => formatPercentFor(locale, number),
      plural: (count, forms) => pluralFor(locale, count, forms),
      enumText: (group, item) => enumTextFor(locale, group, item),
      catalogText: (id, field, fallback) =>
        catalogTextFor(locale, id, field, fallback),
    }),
    [locale, setLocale],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within I18nProvider");
  return context;
}
